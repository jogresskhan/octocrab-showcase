//! `achievements` — enrich the account and farm GitHub achievement badges:
//! `Public` (first public repo), `Quickdraw` (fast issue close), `Pull Shark`
//! (merged PR), `YOLO` (merged without review), `Starstruck` engagement etc.
//! Every step is logged to the `achievements` table.

use crate::cmd::auth::open_client;
use crate::util::*;
use anyhow::Result;
use serde_json::json;

const SHOWCASE: &str = "octocrab-showcase";

pub async fn show() -> Result<()> {
    let (db, octo) = open_client()?;
    let user = octo
        .get::<serde_json::Value, _, _>("/user", None::<&[(&str, &str)]>)
        .await?;
    let g = |k: &str| user.get(k).cloned().unwrap_or(serde_json::Value::Null);
    println!(
        "{} — profile completeness for achievements",
        bold(g("login").as_str().unwrap_or("?"))
    );
    println!();
    let fields = [
        ("name", "Name set"),
        ("bio", "Bio set"),
        ("company", "Company set"),
        ("location", "Location set"),
        ("blog", "Website set"),
        ("twitter_username", "Twitter set"),
    ];
    for (key, label) in fields {
        let val = g(key);
        let present = !val.is_null() && val.as_str().map(|s| !s.is_empty()).unwrap_or(false);
        println!("  {} {}", if present { ok("✓") } else { err("✗") }, label);
    }
    println!();
    println!(
        "public repos: {} • followers: {} • following: {}",
        g("public_repos"),
        g("followers"),
        g("following")
    );
    println!();
    let boosts = db.achievements();
    if boosts.is_empty() {
        println!(
            "{}",
            dim("no achievement actions run yet — try `achievements boost --yes`")
        );
    } else {
        let t = Table::new(&[24, 60, 6]);
        t.row(&["ACTION", "DETAIL", "OK"]);
        for (ts, _action, detail, okk) in boosts {
            t.row(&[
                fmt_ts(ts).get(0..16).unwrap_or("").to_string(),
                trunc(&detail, 59),
                (if okk { "✓" } else { "✗" }).to_string(),
            ]);
        }
    }
    Ok(())
}

pub async fn boost(yes: bool, org: Option<String>) -> Result<()> {
    if !yes {
        anyhow::bail!("this will write to your GitHub account — re-run with --yes to confirm");
    }
    let (db, octo) = open_client()?;
    let login = db
        .get_meta("auth_login")
        .ok_or_else(|| anyhow::anyhow!("run `octocrab-cli auth check` first"))?;
    println!(
        "{} boosting account achievements for {}",
        cyan("★"),
        bold(&login)
    );

    // 1. profile enrichment -------------------------------------------------
    let user = octo
        .get::<serde_json::Value, _, _>("/user", None::<&[(&str, &str)]>)
        .await?;
    let mut patch = serde_json::Map::new();
    let empty = |v: &serde_json::Value| {
        v.is_null() || v.as_str().map(|s| s.trim().is_empty()).unwrap_or(true)
    };
    if empty(&user["bio"]) {
        patch.insert(
            "bio".into(),
            json!("GitHub power user — driving the Octocrab Suite (CLI + Tauri + egui IDE)"),
        );
    }
    if empty(&user["location"]) {
        patch.insert("location".into(), json!("The Cloud"));
    }
    if empty(&user["blog"]) {
        patch.insert("blog".into(), json!("https://github.com/octocrab"));
    }
    if !patch.is_empty() {
        let patch_body = serde_json::Value::Object(patch);
        let r = octo
            .patch::<serde_json::Value, _, _>("/user", Some(&patch_body))
            .await;
        let okv = r.is_ok();
        db.add_achievement("profile", "profile fields enriched", okv)?;
        println!(
            "  {} profile enrichment",
            if okv { ok("✓") } else { err("✗") }
        );
    } else {
        println!("  {} profile already complete", ok("✓"));
    }

    // 2. ensure showcase repo → achievement: Public -------------------------
    let full = format!("{login}/{SHOWCASE}");
    let exists = octo
        .get::<serde_json::Value, _, _>(&format!("/repos/{full}"), None::<&[(&str, &str)]>)
        .await
        .is_ok();
    if !exists {
        let repo_payload = json!({
            "name": SHOWCASE,
            "private": false,
            "auto_init": true,
            "description": "Showcase repo generated by the Octocrab Suite — CLI + Tauri + egui IDE"
        });
        let r = octo
            .post::<_, serde_json::Value>("/user/repos", Some(&repo_payload))
            .await;
        match r {
            Ok(_) => {
                db.add_achievement(
                    "repo",
                    "created public repo octocrab-showcase (→ Public badge)",
                    true,
                )?;
                println!("  {} created {}", ok("✓"), bold(&full));
            }
            Err(e) => {
                db.add_achievement("repo", &format!("repo create failed: {e}"), false)?;
                println!(
                    "  {} repo creation failed: {}",
                    err("✗"),
                    dim(&e.to_string())
                );
            }
        }
    } else {
        println!("  {} {} already exists", ok("✓"), bold(&full));
    }

    // 3. issue opened + closed fast → achievement: Quickdraw ----------------
    let issue = octo
        .issues(&login, SHOWCASE)
        .create("Suite capability check")
        .body("Automated capability smoke-test by octocrab-cli.\n\n- [x] opened\n- [x] closed within 5 minutes → **Quickdraw**")
        .send()
        .await;
    if let Ok(issue) = issue {
        let closed = octo
            .patch::<serde_json::Value, _, _>(
                &format!("/repos/{full}/issues/{}", issue.number),
                Some(&json!({"state": "closed"})),
            )
            .await
            .is_ok();
        db.add_achievement(
            "quickdraw",
            &format!("issue #{} opened & closed (→ Quickdraw)", issue.number),
            closed,
        )?;
        println!(
            "  {} issue #{} opened+closed",
            if closed { ok("✓") } else { err("✗") },
            issue.number
        );
    } else {
        db.add_achievement("quickdraw", "issues:write locked", false)?;
        println!("  {} issue step skipped (issues:write locked)", warn("!"));
    }

    // 4. branch → commit → PR → merge → Pull Shark + YOLO --------------------
    match pr_pipeline(&octo, &login).await {
        Ok(Some(msg)) => {
            db.add_achievement("pull-shark", &msg, true)?;
            println!("  {} {msg}", ok("✓"));
        }
        Ok(None) => {
            println!("  {} PR step skipped", warn("!"));
        }
        Err(e) => {
            db.add_achievement("pull-shark", &format!("pr pipeline failed: {e}"), false)?;
            println!("  {} PR pipeline: {}", err("✗"), dim(&e.to_string()));
        }
    }

    // 5. star popular repos → community engagement ---------------------------
    let mut starred = 0;
    if let Ok(page) = octo
        .get::<serde_json::Value, _, _>(
            "/search/repositories",
            Some(&[("q", "stars:>50000 language:rust"), ("per_page", "3")]),
        )
        .await
    {
        if let Some(items) = page.get("items").and_then(|v| v.as_array()) {
            for repo in items {
                let owner = repo
                    .pointer("/owner/login")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default()
                    .to_string();
                let name = repo
                    .get("name")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default()
                    .to_string();
                if octo.current().star_repo(&owner, &name).await.is_ok() {
                    starred += 1;
                }
            }
        }
    }
    db.add_achievement(
        "stars",
        &format!("starred {starred} popular rust repos"),
        starred > 0,
    )?;
    println!(
        "  {} starred {starred} repositories",
        if starred > 0 { ok("✓") } else { warn("!") }
    );

    // 6. gist → engagement ---------------------------------------------------
    let gist_payload = json!({
        "description": "Octocrab Suite session snapshot",
        "public": false,
        "files": {
            "octocrab-suite.md": {"content": format!("# Octocrab Suite\n\nSession initialized for @{login} on {}.\n\n- CLI: octocrab-cli\n- IDE: octocrab-ide (egui)\n- GUI: octocrab-tauri\n", chrono::Utc::now().to_rfc3339())}
        }
    });
    let gist = octo
        .post::<_, serde_json::Value>("/gists", Some(&gist_payload))
        .await;
    match gist {
        Ok(_) => {
            db.add_achievement("gist", "created session gist", true)?;
            println!("  {} session gist created", ok("✓"));
        }
        Err(e) => {
            db.add_achievement("gist", &format!("gist failed: {e}"), false)?;
            println!("  {} gist skipped ({})", warn("!"), dim(&e.to_string()));
        }
    }

    // 7. optional org ---------------------------------------------------------
    if let Some(org) = org {
        let org_payload = json!({"login": org, "profile_name": org});
        let r = octo
            .post::<_, serde_json::Value>("/organizations", Some(&org_payload))
            .await;
        let okv = r.is_ok();
        db.add_achievement("org", &format!("organization '{org}' creation"), okv)?;
        println!(
            "  {} organization '{org}': {}",
            if okv { ok("✓") } else { err("✗") },
            if okv {
                "created"
            } else {
                "needs billing/admin rights"
            }
        );
    }

    println!();
    println!(
        "{}",
        ok("boost complete — check https://github.com/{login} for new badges")
    );
    Ok(())
}

/// branch → commit → PR → merge (all through octocrab).
async fn pr_pipeline(
    octo: &std::sync::Arc<octocrab::Octocrab>,
    login: &str,
) -> Result<Option<String>> {
    let full = format!("{login}/{SHOWCASE}");
    let repo = octo
        .get::<serde_json::Value, _, _>(&format!("/repos/{full}"), None::<&[(&str, &str)]>)
        .await?;
    let base = repo
        .get("default_branch")
        .and_then(|v| v.as_str())
        .unwrap_or("main")
        .to_string();

    let refdata = octo
        .get::<serde_json::Value, _, _>(
            &format!("/repos/{full}/git/ref/heads/{base}"),
            None::<&[(&str, &str)]>,
        )
        .await?;
    let sha = refdata
        .pointer("/object/sha")
        .and_then(|v| v.as_str())
        .ok_or_else(|| anyhow::anyhow!("cannot resolve default branch sha"))?
        .to_string();

    let branch = format!(
        "octocrab-suite-{}",
        chrono::Utc::now().format("%Y%m%d%H%M%S")
    );
    let ref_payload = json!({"ref": format!("refs/heads/{branch}"), "sha": sha});
    octo.post::<_, serde_json::Value>(&format!("/repos/{full}/git/refs"), Some(&ref_payload))
        .await?;

    octo.repos(login, SHOWCASE)
        .create_file(
            format!("notes/{branch}.md"),
            format!("add note from {branch}"),
            format!(
                "# Suite note\n\nGenerated by octocrab-cli at {}.\n",
                chrono::Utc::now().to_rfc3339()
            ),
        )
        .branch(&branch)
        .send()
        .await?;

    let pr_payload = json!({
        "title": "Add suite note",
        "head": branch,
        "base": base,
        "body": "Automated PR from the Octocrab Suite → **Pull Shark** + **YOLO**"
    });
    let pr = octo
        .post::<_, serde_json::Value>(&format!("/repos/{full}/pulls"), Some(&pr_payload))
        .await?;
    let number = pr.get("number").and_then(|v| v.as_i64()).unwrap_or(0);

    let merge_payload = json!({"merge_method": "merge"});
    let merged = octo
        .put::<serde_json::Value, _, _>(
            &format!("/repos/{full}/pulls/{number}/merge"),
            Some(&merge_payload),
        )
        .await;
    match merged {
        Ok(_) => Ok(Some(format!("PR #{number} merged (→ Pull Shark + YOLO)"))),
        Err(e) => Err(anyhow::anyhow!("merge failed for PR #{number}: {e}")),
    }
}
